import { useState, useEffect } from 'react';
import { useLanguage } from '@/contexts/LanguageContext';
import { supabase } from '@/integrations/supabase/client';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { Textarea } from '@/components/ui/textarea';
import { Label } from '@/components/ui/label';
import { useToast } from '@/hooks/use-toast';
import { FileText, ArrowLeft, ArrowRight, User, Building, Mail, Phone, MessageSquare } from 'lucide-react';
import type { OrderData } from '@/pages/Subscribe';
import { z } from 'zod';

interface FormStepProps {
  orderData: OrderData;
  updateOrderData: (data: Partial<OrderData>) => void;
  onComplete: (orderId: string) => void;
  onBack: () => void;
  isRenewal?: boolean;
  renewalOrderId?: string | null;
}

const formSchema = z.object({
  fullName: z.string().min(2),
  businessName: z.string().min(2),
  email: z.string().email(),
  phone: z.string().min(10),
  whatsapp: z.string().min(10),
});

const FormStep = ({ orderData, updateOrderData, onComplete, onBack, isRenewal = false, renewalOrderId }: FormStepProps) => {
  const { isRTL } = useLanguage();
  const { toast } = useToast();
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [formData, setFormData] = useState({
    fullName: orderData.fullName,
    businessName: orderData.businessName,
    email: orderData.email,
    phone: orderData.phone,
    whatsapp: orderData.whatsapp,
    websiteRequirements: orderData.websiteRequirements,
  });

  useEffect(() => {
    // Pre-fill from logged in user if available
    const checkUser = async () => {
      const { data: { session } } = await supabase.auth.getSession();
      if (session?.user) {
        const { data: profile } = await supabase
          .from('profiles')
          .select('*')
          .eq('id', session.user.id)
          .single();
        
        if (profile) {
          setFormData(prev => ({
            ...prev,
            fullName: profile.full_name || prev.fullName,
            email: session.user.email || prev.email,
            phone: profile.phone || prev.phone,
            whatsapp: profile.whatsapp || profile.phone || prev.whatsapp,
          }));
        } else {
          setFormData(prev => ({
            ...prev,
            email: session.user.email || prev.email,
          }));
        }
      }
    };
    checkUser();
  }, []);

  const handleSubmit = async () => {
    const validation = formSchema.safeParse(formData);
    if (!validation.success) {
      toast({
        variant: 'destructive',
        title: isRTL ? 'خطأ في البيانات' : 'Invalid data',
        description: isRTL ? 'يرجى ملء جميع الحقول بشكل صحيح' : 'Please fill all fields correctly',
      });
      return;
    }

    setIsSubmitting(true);

    try {
      const { data: { session } } = await supabase.auth.getSession();
      
      if (isRenewal && renewalOrderId) {
        // Update existing order for renewal
        const { error } = await supabase
          .from('orders')
          .update({
            subscription_status: 'renewed',
            renewal_date: new Date(Date.now() + 30 * 24 * 60 * 60 * 1000).toISOString(),
            receipt_url: orderData.receiptUrl,
            payment_method: orderData.paymentMethod,
          })
          .eq('order_id', renewalOrderId);

        if (error) throw error;
        onComplete(renewalOrderId);
      } else {
        // Create new order - order_id is generated by database trigger
        const insertData: {
          order_id: string;
          full_name: string;
          business_name: string;
          email: string;
          phone: string;
          whatsapp: string;
          website_requirements: string;
          setup_fee: number;
          monthly_fee: number;
          custom_domain_addon: boolean;
          business_email_addon: boolean;
          addon_total: number;
          payment_method: string;
          receipt_url: string;
          coupon_code: string | null;
          coupon_discount: number;
          user_id?: string;
        } = {
          order_id: '', // Will be generated by trigger
          full_name: formData.fullName,
          business_name: formData.businessName,
          email: formData.email,
          phone: formData.phone,
          whatsapp: formData.whatsapp,
          website_requirements: formData.websiteRequirements,
          setup_fee: orderData.setupFee,
          monthly_fee: orderData.monthlyFee,
          custom_domain_addon: orderData.customDomainAddon,
          business_email_addon: orderData.businessEmailAddon,
          addon_total: orderData.addonTotal,
          payment_method: orderData.paymentMethod,
          receipt_url: orderData.receiptUrl,
          coupon_code: orderData.couponCode || null,
          coupon_discount: orderData.couponDiscount || 0,
        };
        
        // Add user_id if logged in
        if (session?.user?.id) {
          insertData.user_id = session.user.id;
        }
        
        const { data, error } = await supabase
          .from('orders')
          .insert([insertData])
          .select('order_id')
          .single();

        if (error) throw error;
        
        // Increment coupon usage count if a coupon was used
        if (orderData.couponCode) {
          const { data: couponData } = await supabase
            .from('coupons')
            .select('usage_count')
            .eq('code', orderData.couponCode)
            .single();
          
          if (couponData) {
            await supabase
              .from('coupons')
              .update({ usage_count: couponData.usage_count + 1 })
              .eq('code', orderData.couponCode);
          }
        }
        
        
        onComplete(data.order_id);
      }

      toast({
        title: isRTL ? 'تم إرسال الطلب بنجاح' : 'Order submitted successfully',
      });
    } catch (error) {
      console.error('Submit error:', error);
      toast({
        variant: 'destructive',
        title: isRTL ? 'حدث خطأ' : 'Error occurred',
        description: isRTL ? 'يرجى المحاولة مرة أخرى' : 'Please try again',
      });
    } finally {
      setIsSubmitting(false);
    }
  };

  const BackArrowIcon = isRTL ? ArrowRight : ArrowLeft;

  return (
    <div className="glass rounded-3xl p-8 gradient-border">
      <div className={`flex items-center gap-3 mb-6 ${isRTL ? 'flex-row-reverse' : ''}`}>
        <div className="w-12 h-12 rounded-xl gradient-bg flex items-center justify-center">
          <FileText className="w-6 h-6 text-white" />
        </div>
        <div>
          <h2 className={`text-xl font-bold ${isRTL ? 'text-right' : ''}`}>
            {isRTL ? 'بيانات الاشتراك' : 'Subscription Details'}
          </h2>
          <p className={`text-muted-foreground text-sm ${isRTL ? 'text-right' : ''}`}>
            {isRTL ? 'أدخل بياناتك لإتمام الطلب' : 'Enter your details to complete the order'}
          </p>
        </div>
      </div>

      <div className="space-y-4 mb-6">
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          <div className="space-y-2">
            <Label htmlFor="fullName" className={isRTL ? 'text-right block' : ''}>
              {isRTL ? 'الاسم الكامل' : 'Full Name'}
            </Label>
            <div className="relative">
              <User className={`absolute top-1/2 -translate-y-1/2 w-5 h-5 text-muted-foreground ${isRTL ? 'right-3' : 'left-3'}`} />
              <Input
                id="fullName"
                value={formData.fullName}
                onChange={(e) => setFormData(prev => ({ ...prev, fullName: e.target.value }))}
                className={isRTL ? 'pr-10 text-right' : 'pl-10'}
                placeholder={isRTL ? 'أدخل اسمك الكامل' : 'Enter your full name'}
                required
              />
            </div>
          </div>

          <div className="space-y-2">
            <Label htmlFor="businessName" className={isRTL ? 'text-right block' : ''}>
              {isRTL ? 'اسم النشاط التجاري' : 'Business Name'}
            </Label>
            <div className="relative">
              <Building className={`absolute top-1/2 -translate-y-1/2 w-5 h-5 text-muted-foreground ${isRTL ? 'right-3' : 'left-3'}`} />
              <Input
                id="businessName"
                value={formData.businessName}
                onChange={(e) => setFormData(prev => ({ ...prev, businessName: e.target.value }))}
                className={isRTL ? 'pr-10 text-right' : 'pl-10'}
                placeholder={isRTL ? 'أدخل اسم النشاط' : 'Enter your business name'}
                required
              />
            </div>
          </div>
        </div>

        <div className="space-y-2">
          <Label htmlFor="email" className={isRTL ? 'text-right block' : ''}>
            {isRTL ? 'البريد الإلكتروني' : 'Email'}
          </Label>
          <div className="relative">
            <Mail className={`absolute top-1/2 -translate-y-1/2 w-5 h-5 text-muted-foreground ${isRTL ? 'right-3' : 'left-3'}`} />
            <Input
              id="email"
              type="email"
              value={formData.email}
              onChange={(e) => setFormData(prev => ({ ...prev, email: e.target.value }))}
              className={isRTL ? 'pr-10 text-right' : 'pl-10'}
              placeholder={isRTL ? 'أدخل بريدك الإلكتروني' : 'Enter your email'}
              required
            />
          </div>
        </div>

        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          <div className="space-y-2">
            <Label htmlFor="phone" className={isRTL ? 'text-right block' : ''}>
              {isRTL ? 'رقم الهاتف' : 'Phone Number'}
            </Label>
            <div className="relative">
              <Phone className={`absolute top-1/2 -translate-y-1/2 w-5 h-5 text-muted-foreground ${isRTL ? 'right-3' : 'left-3'}`} />
              <Input
                id="phone"
                type="tel"
                value={formData.phone}
                onChange={(e) => setFormData(prev => ({ ...prev, phone: e.target.value }))}
                className={isRTL ? 'pr-10 text-right' : 'pl-10'}
                placeholder={isRTL ? 'أدخل رقم الهاتف' : 'Enter phone number'}
                required
              />
            </div>
          </div>

          <div className="space-y-2">
            <Label htmlFor="whatsapp" className={isRTL ? 'text-right block' : ''}>
              {isRTL ? 'رقم الواتساب' : 'WhatsApp Number'}
            </Label>
            <div className="relative">
              <MessageSquare className={`absolute top-1/2 -translate-y-1/2 w-5 h-5 text-muted-foreground ${isRTL ? 'right-3' : 'left-3'}`} />
              <Input
                id="whatsapp"
                type="tel"
                value={formData.whatsapp}
                onChange={(e) => setFormData(prev => ({ ...prev, whatsapp: e.target.value }))}
                className={isRTL ? 'pr-10 text-right' : 'pl-10'}
                placeholder={isRTL ? 'أدخل رقم الواتساب' : 'Enter WhatsApp number'}
                required
              />
            </div>
          </div>
        </div>

        {!isRenewal && (
          <div className="space-y-2">
            <Label htmlFor="requirements" className={isRTL ? 'text-right block' : ''}>
              {isRTL ? 'متطلبات الموقع' : 'Website Requirements'}
            </Label>
            <Textarea
              id="requirements"
              value={formData.websiteRequirements}
              onChange={(e) => setFormData(prev => ({ ...prev, websiteRequirements: e.target.value }))}
              className={isRTL ? 'text-right' : ''}
              placeholder={isRTL ? 'أخبرنا عن متطلبات موقعك...' : 'Tell us about your website requirements...'}
              rows={4}
            />
          </div>
        )}
      </div>

      {/* Buttons */}
      <div className={`flex gap-3 ${isRTL ? 'flex-row-reverse' : ''}`}>
        <Button
          variant="outline"
          onClick={onBack}
          className={`flex items-center gap-2 ${isRTL ? 'flex-row-reverse' : ''}`}
        >
          <BackArrowIcon className="w-4 h-4" />
          {isRTL ? 'السابق' : 'Back'}
        </Button>
        <Button
          onClick={handleSubmit}
          disabled={isSubmitting}
          className="flex-1 gradient-bg hover:opacity-90 text-lg py-6"
        >
          {isSubmitting 
            ? (isRTL ? 'جاري الإرسال...' : 'Submitting...')
            : (isRTL ? 'ادفع واشترك' : 'Pay & Subscribe')
          }
        </Button>
      </div>
    </div>
  );
};

export default FormStep;
